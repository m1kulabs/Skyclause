import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, realpathSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import * as prettier from 'prettier'

export interface GenerateReplayDataOptions {
  sourcePath: string
  outputPath: string
}

const KNOWN_FIXTURE_RELATIVE = 'pilot/fixtures/rainfall-graph-75-20261105T1312Z.json'
const KNOWN_FIXTURE_SHA256 = '25cae3be496cff29b9925595d23fc63b7ddf9c1a4fb29e22b806b00d4ed3bd95'
const EXPECTED_STATION_ID = '0232901RF'
const REPLAY_DATE = '2026-11-02'
const EXPECTED_RECORD_COUNT = 288

const DEFAULT_SOURCE_PATH = fileURLToPath(new URL('../fixtures/rainfall-graph-75-20261105T1312Z.json', import.meta.url))
const DEFAULT_OUTPUT_PATH = fileURLToPath(new URL('./src/replay-data.ts', import.meta.url))

interface RawJpsPoint {
  timestamp: string
  rf: number
  dailyrf: number
}

function tryRealpath(targetPath: string): string {
  try {
    return realpathSync(targetPath)
  } catch {
    return resolve(targetPath)
  }
}

export async function generateReplayData(options: GenerateReplayDataOptions): Promise<void> {
  if (!options || typeof options.sourcePath !== 'string' || typeof options.outputPath !== 'string') {
    throw new Error('generateReplayData requires sourcePath and outputPath strings')
  }

  const resolvedSource = resolve(options.sourcePath)
  const resolvedOutput = resolve(options.outputPath)
  const canonicalSource = tryRealpath(resolvedSource)
  const canonicalOutput = tryRealpath(resolvedOutput)
  const canonicalDefaultSource = tryRealpath(DEFAULT_SOURCE_PATH)

  if (canonicalSource === canonicalOutput || canonicalOutput === canonicalDefaultSource) {
    throw new Error('Output path must not point to the replay source fixture')
  }

  const rawBytes = readFileSync(resolvedSource)
  const actualSha256 = createHash('sha256').update(rawBytes).digest('hex')
  if (actualSha256 !== KNOWN_FIXTURE_SHA256) {
    throw new Error(`Replay fixture SHA-256 mismatch: expected ${KNOWN_FIXTURE_SHA256}, got ${actualSha256}`)
  }

  const parsed = JSON.parse(rawBytes.toString('utf8')) as unknown
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) {
    throw new Error('Replay fixture root must be an object')
  }

  const record = parsed as Record<string, unknown>
  if (record.stationId !== EXPECTED_STATION_ID) {
    throw new Error(`Expected stationId ${EXPECTED_STATION_ID}, got ${String(record.stationId)}`)
  }
  if (!Array.isArray(record.data)) {
    throw new Error('Replay fixture data must be an array')
  }

  const nov2Points: RawJpsPoint[] = []
  for (const item of record.data) {
    if (!item || typeof item !== 'object' || Array.isArray(item)) {
      throw new Error('Replay fixture data entry must be an object')
    }
    const row = item as Record<string, unknown>
    if (typeof row.timestamp !== 'string') {
      throw new Error('Replay fixture data entry missing string timestamp')
    }
    if (!row.timestamp.startsWith(`${REPLAY_DATE}T`)) {
      continue
    }
    if (typeof row.rf !== 'number' || !Number.isFinite(row.rf)) {
      throw new Error(`Invalid rf at ${row.timestamp}`)
    }
    if (typeof row.dailyrf !== 'number' || !Number.isFinite(row.dailyrf)) {
      throw new Error(`Invalid dailyrf at ${row.timestamp}`)
    }
    nov2Points.push({
      timestamp: row.timestamp,
      rf: row.rf,
      dailyrf: row.dailyrf
    })
  }

  if (nov2Points.length !== EXPECTED_RECORD_COUNT) {
    throw new Error(`Expected ${EXPECTED_RECORD_COUNT} records for ${REPLAY_DATE}, got ${nov2Points.length}`)
  }

  const sourceMetadata = {
    fixture: KNOWN_FIXTURE_RELATIVE,
    sha256: KNOWN_FIXTURE_SHA256,
    replayDate: REPLAY_DATE,
    stationId: EXPECTED_STATION_ID
  }

  const captureLiteral = {
    stationId: EXPECTED_STATION_ID,
    data: nov2Points
  }

  const unformatted = [
    '// Generated by pilot/apps-script/generate-replay-data.ts from the verified 2 Nov 2026 JPS capture.',
    '// Do not edit by hand.',
    `export const JPS_REPLAY_SOURCE = ${JSON.stringify(sourceMetadata, null, 2)} as const`,
    '',
    `export const JPS_REPLAY_CAPTURE = ${JSON.stringify(captureLiteral, null, 2)} as const`,
    ''
  ].join('\n')

  const prettierConfig = (await prettier.resolveConfig(DEFAULT_OUTPUT_PATH)) ?? {}
  const formatted = await prettier.format(unformatted, {
    ...prettierConfig,
    parser: 'typescript'
  })

  mkdirSync(dirname(resolvedOutput), { recursive: true })
  writeFileSync(resolvedOutput, formatted, 'utf8')
}

if (import.meta.main) {
  await generateReplayData({
    sourcePath: DEFAULT_SOURCE_PATH,
    outputPath: DEFAULT_OUTPUT_PATH
  })
}
