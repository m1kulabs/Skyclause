// `bun run --cwd packages/db generate:auth [--check] [--config <path>]` writes (or, with --check, compares)
// src/schema/auth.ts from the Better Auth CLI's Drizzle output for auth.config.ts, or for another config such as #94's
// runtime one. It moves every table into the `auth` schema, defaults IDs to
// uuidv7() (#79 conventions) and stores instants as timestamptz (UTC), then formats with Prettier. After a change, run
// `bun run --cwd packages/db generate -- --name <plan key>-<what>` for the migration.
import { spawnSync } from 'node:child_process'
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { format, resolveConfig } from 'prettier'

const pkg = fileURLToPath(new URL('..', import.meta.url))
const target = join(pkg, 'src/schema/auth.ts')
const scratch = mkdtempSync(join(tmpdir(), 'skyclause-auth-'))
const at = process.argv.indexOf('--config')
const config = at > 0 ? process.argv[at + 1]! : 'scripts/auth.config.ts'

function rewrite(source: string): string {
  const body = source
    .replace(/\bpgTable,\s*/, 'pgSchema,\n')
    .replace(/\bpgTable\(/g, 'authSchema.table(')
    .replaceAll('pg_catalog.gen_random_uuid()', 'uuidv7()')
    .replace(/timestamp\(("[a-z_]+")\)/g, 'timestamp($1, { withTimezone: true })')
    .replace(/\nexport const /, "\nexport const authSchema = pgSchema('auth')\n\nexport const ")
  return `// Generated by scripts/generate-auth.ts from the Better Auth CLI; edit auth.config.ts and regenerate.\n${body}`
}

try {
  const generated = join(scratch, 'auth.ts')
  const args = ['x', 'auth', 'generate', '--config', config, '--output', generated, '--yes']
  const cli = spawnSync('bun', [...args, '--adapter', 'drizzle', '--dialect', 'postgresql'], {
    cwd: pkg,
    encoding: 'utf8'
  })
  if (cli.status !== 0) throw new Error(`the Better Auth CLI exited ${cli.status}: ${cli.stderr}${cli.stdout}`)
  const source = await format(rewrite(readFileSync(generated, 'utf8')), {
    ...(await resolveConfig(target)),
    filepath: target
  })
  if (process.argv.includes('--check')) {
    if (source !== readFileSync(target, 'utf8')) {
      console.error('src/schema/auth.ts differs from the Better Auth CLI output; run generate:auth')
      process.exitCode = 1
    } else console.log('src/schema/auth.ts matches the Better Auth CLI output')
  } else writeFileSync(target, source)
} finally {
  rmSync(scratch, { recursive: true, force: true })
}
