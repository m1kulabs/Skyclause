import { z } from 'zod'

// Spec §6. Owners add their variables to the service that reads them.
const base = z.object({
  APP_ENV: z.enum(['dev', 'production', 'test']),
  // a-observability; telemetry exports only where Terraform sets GCP_PROJECT (f-infra).
  OTEL_SERVICE_NAME: z.string().min(1).optional(),
  // Unset means info (telemetry.ts).
  LOG_LEVEL: z.enum(['debug', 'info', 'warn', 'error']).optional(),
  GCP_PROJECT: z.string().min(1).optional(),
  GCP_REGION: z.string().min(1).optional()
})

// a-email-transport (#113): infra/aws's app_config output. Optional until gate 4B, then all of a
// service's set together.
const arn = (service: string) => z.string().regex(new RegExp(`^arn:aws:${service}:[a-z0-9-]*:\\d{12}:.+$`))
const sending = {
  SES_REGION: z.string().regex(/^[a-z]{2}(-[a-z]+)+-\d$/),
  SES_CONFIGURATION_SET: z.string().min(1),
  EMAIL_FROM_AUTH: z.string().min(1),
  EMAIL_FROM_NOTICES: z.string().min(1),
  AWS_ROLE_ARN: arn('iam')
}
const receiving = {
  SES_EVENTS_SNS_TOPIC_ARN: arn('sns'),
  INBOUND_DOMAIN: z.string().min(1),
  INBOUND_BUCKET: z.string().min(1),
  INBOUND_SNS_TOPIC_ARN: arn('sns')
}

// c-approver-alerts' VAPID values (#113 generates them): optional until the vapid-keys job has
// run; VAPID_SUBJECT is APP_ORIGIN from Terraform.
const base64urlBytes = (length: number, first?: number) =>
  z.string().refine((value) => {
    const bytes = Buffer.from(value, 'base64url')
    return /^[\w-]+$/.test(value) && bytes.length === length && (first === undefined || bytes[0] === first)
  }, `must be ${length} bytes of base64url`)
const vapidPublic = { VAPID_SUBJECT: z.url().optional(), VAPID_PUBLIC_KEY: base64urlBytes(65, 0x04).optional() }

function optional<T extends Record<string, z.ZodType>>(shape: T) {
  return Object.fromEntries(Object.entries(shape).map(([name, type]) => [name, type.optional()])) as {
    [K in keyof T]: z.ZodOptional<T[K]>
  }
}

function together(names: string[]) {
  return (env: Record<string, unknown>, ctx: z.RefinementCtx) => {
    const missing = names.filter((name) => env[name] === undefined)
    if (missing.length && missing.length < names.length) {
      for (const name of missing)
        ctx.addIssue({ code: 'custom', path: [name], message: 'set with the other email variables' })
    }
  }
}

// f-api (#93): spec §4 Hosts. Unset HOST_MODE is single (laptops and CI); multi needs all six origins, which
// Terraform sets. IP_HASH_KEY keys the rate limiter's IP hash (Secret Manager in production).
const ORIGINS = ['MARKETING_ORIGIN', 'APP_ORIGIN', 'API_ORIGIN', 'MCP_ORIGIN', 'EMBED_ORIGIN', 'DOCS_ORIGIN'] as const
const hosts = {
  HOST_MODE: z.enum(['single', 'multi']).optional(),
  ...(Object.fromEntries(ORIGINS.map((name) => [name, z.url().optional()])) as Record<
    (typeof ORIGINS)[number],
    z.ZodOptional<z.ZodURL>
  >),
  IP_HASH_KEY: z.string().min(32)
}

function multiNeedsOrigins(env: Record<string, unknown>, ctx: z.RefinementCtx) {
  if (env.HOST_MODE === 'multi') {
    for (const name of ORIGINS.filter((name) => env[name] === undefined)) {
      ctx.addIssue({ code: 'custom', path: [name], message: 'required when HOST_MODE is multi' })
    }
  }
}

// f-auth (#94): Better Auth's signing secret (generated in Secret Manager) and D30's staff addresses, comma-separated;
// the staff secret starts empty until #118 fills it.
const auth = {
  BETTER_AUTH_SECRET: z.string().min(32),
  SKYCLAUSE_STAFF_EMAILS: z.string().optional()
}

// c-subscribers (#157): EMAIL_HASH_KEY keys `emailHash` for suppressions (Secret Manager, generated by #89).
const emailHashKey = { EMAIL_HASH_KEY: z.string().min(32) }

const schemas = {
  web: base
    .extend({ ...optional(sending), ...vapidPublic, ...hosts, ...auth, ...emailHashKey })
    .superRefine(together(Object.keys(sending)))
    .superRefine(multiNeedsOrigins),
  worker: base
    .extend({
      WORKER_URL: z.url(),
      WORKER_INVOKER_SA: z.email(),
      PORT: z.coerce.number().int().positive().default(8080),
      // c-recipient-replies (#163), c-sender-email (#158), c-approver-alerts (#155): the links in feedback, notice and
      // approver alert emails (Terraform sets every
      // origin on every service) and the suppression hash.
      APP_ORIGIN: z.url().optional(),
      MARKETING_ORIGIN: z.url().optional(),
      ...emailHashKey,
      ...optional(sending),
      ...optional(receiving),
      ...vapidPublic,
      VAPID_PRIVATE_KEY: base64urlBytes(32).optional()
    })
    .superRefine(together([...Object.keys(sending), ...Object.keys(receiving)])),
  // GCP_PROJECT is f-infra's; the vapid-keys job reads it.
  job: base.extend({ GCP_PROJECT: z.string().min(1).optional() })
}

export type Service = keyof typeof schemas
export type Env<S extends Service> = z.infer<(typeof schemas)[S]>

export function loadEnv<S extends Service>(
  service: S,
  source: Record<string, string | undefined> = process.env
): Env<S> {
  if (source.APP_ENV === 'test' && (source.K_SERVICE || source.CLOUD_RUN_JOB)) {
    throw new Error('APP_ENV=test is refused on Cloud Run (K_SERVICE or CLOUD_RUN_JOB is set)')
  }
  const result = schemas[service].safeParse(source)
  if (!result.success) {
    const problems = result.error.issues.map((issue) => `${issue.path.join('.')}: ${issue.message}`)
    throw new Error(`${service} environment is invalid: ${problems.join('; ')}`)
  }
  return result.data as Env<S>
}
