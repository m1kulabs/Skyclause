// Regenerates src/confusables.ts from Unicode's confusables.txt (UTS #39):
//   bun packages/agent/scripts/confusables.ts <path to confusables.txt>
//   bunx prettier --write packages/agent/src/confusables.ts
// Keeps the single-character sources whose skeleton is plain ASCII letters, the only ones validate's word checks need.
import { readFileSync, writeFileSync } from 'node:fs'

const path = process.argv[2]
if (!path) throw new Error('usage: bun scripts/confusables.ts <confusables.txt>')
const text = readFileSync(path, 'utf8')
const version = text.match(/^# Version: (.+)$/m)?.[1]
const date = text.match(/^# Date: (.+)$/m)?.[1]
const byTarget = new Map<string, string>()
for (const line of text.split('\n')) {
  const [source, target] = line
    .split('#')[0]!
    .split(';')
    .map((s) => s.trim())
  if (!source || !target || source.includes(' ')) continue
  const to = target
    .split(' ')
    .map((hex) => String.fromCodePoint(parseInt(hex, 16)))
    .join('')
  const from = String.fromCodePoint(parseInt(source, 16))
  if (!/^[A-Za-z]+$/.test(to) || from.codePointAt(0)! < 0x80) continue
  byTarget.set(to, (byTarget.get(to) ?? '') + from)
}
const rows = [...byTarget]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([to, from]) => `  ${JSON.stringify(to)}: ${JSON.stringify(from)}`)
writeFileSync(
  new URL('../src/confusables.ts', import.meta.url),
  `// Generated by scripts/confusables.ts from Unicode confusables.txt (UTS #39), version ${version}, ${date}.
// Each key is an ASCII letter sequence; its value lists the single characters whose skeleton it is.
export const CONFUSABLE_LETTERS: Record<string, string> = {\n${rows.join(',\n')}\n}\n`
)
