import { afterEach, expect, test, vi } from 'vitest'
import { createUndoableAction } from '../../features/settings/set-7/undoable-action'

afterEach(() => vi.useRealTimers())

test('defers the only write for exactly 10 seconds', async () => {
  vi.useFakeTimers()
  const commit = vi.fn()
  const action = createUndoableAction(commit)
  action.start()
  expect(action.getSnapshot().pending).toBe(true)
  await vi.advanceTimersByTimeAsync(9_999)
  expect(commit).not.toHaveBeenCalled()
  await vi.advanceTimersByTimeAsync(1)
  expect(commit).toHaveBeenCalledExactlyOnceWith({ keepalive: false })
  expect(action.getSnapshot().pending).toBe(false)
})

test('Undo cancels the write rather than writing and reversing', async () => {
  vi.useFakeTimers()
  const commit = vi.fn()
  const action = createUndoableAction(commit)
  action.start()
  await vi.advanceTimersByTimeAsync(9_999)
  action.undo()
  await vi.advanceTimersByTimeAsync(20_000)
  action.flush()
  expect(commit).not.toHaveBeenCalled()
})

test('pagehide flushes once with keepalive and clears the deadline', async () => {
  vi.useFakeTimers()
  const commit = vi.fn()
  const lifecycle = new EventTarget()
  const action = createUndoableAction(commit, lifecycle)
  action.start()
  lifecycle.dispatchEvent(new Event('pagehide'))
  lifecycle.dispatchEvent(new Event('pagehide'))
  await vi.advanceTimersByTimeAsync(10_000)
  expect(commit).toHaveBeenCalledExactlyOnceWith({ keepalive: true })
})

test('unmounting a subscriber preserves the deadline and the pagehide fallback', async () => {
  vi.useFakeTimers()
  const commit = vi.fn()
  const lifecycle = new EventTarget()
  const action = createUndoableAction(commit, lifecycle)
  const unmount = action.subscribe(vi.fn())
  action.start()
  unmount()
  await vi.advanceTimersByTimeAsync(9_999)
  expect(commit).not.toHaveBeenCalled()
  lifecycle.dispatchEvent(new Event('pagehide'))
  await vi.advanceTimersByTimeAsync(10_000)
  expect(commit).toHaveBeenCalledExactlyOnceWith({ keepalive: true })
})

test('does not replace a pending or in-flight action', async () => {
  vi.useFakeTimers()
  let finish!: () => void
  const commit = vi.fn(() => new Promise<void>((resolve) => (finish = resolve)))
  const action = createUndoableAction(commit)
  expect(action.start()).toBe(true)
  expect(action.start()).toBe(false)
  await vi.advanceTimersByTimeAsync(10_000)
  expect(action.start()).toBe(false)
  action.undo()
  expect(commit).toHaveBeenCalledTimes(1)
  finish()
  await Promise.resolve()
  expect(action.start()).toBe(true)
  action.undo()
})

test('reports a failed commit without retrying or reversing it', async () => {
  vi.useFakeTimers()
  const error = new Error('Network unavailable')
  const commit = vi.fn().mockRejectedValue(error)
  const action = createUndoableAction(commit)
  action.start()
  await vi.advanceTimersByTimeAsync(10_000)
  expect(action.getSnapshot()).toEqual({ pending: false, committing: false, error })
  await vi.advanceTimersByTimeAsync(10_000)
  expect(commit).toHaveBeenCalledTimes(1)
})

test('captures the queued object callback rather than a later selection', async () => {
  vi.useFakeTimers()
  const initial = vi.fn()
  const selected = vi.fn()
  const laterSelection = vi.fn()
  const action = createUndoableAction(initial)
  action.start(selected)
  expect(action.start(laterSelection)).toBe(false)
  await vi.advanceTimersByTimeAsync(10_000)
  expect(selected).toHaveBeenCalledExactlyOnceWith({ keepalive: false })
  expect(initial).not.toHaveBeenCalled()
  expect(laterSelection).not.toHaveBeenCalled()
})
